/*
 * Device kernel source, shared by the OpenCL and CUDA backends.
 *
 * The kernels are written in the common subset of OpenCL C and CUDA C: only
 * one-dimensional global indices, plain scalar types and no local memory, so
 * the very same source string is compiled by clCreateProgramWithSource and by
 * the CUDA runtime (backend_cuda.c prepends a small typedef/macro header).
 * Keeping a single source of truth means the numerically sensitive integer
 * transforms can never drift between the two GPU paths -- and both are
 * bit-identical to the CPU reference implementation, which is what makes the
 * hybrid dispatch safe: moving a stage to the GPU cannot change the output
 * bitstream, only the speed at which it is produced.
 *
 * Quantisation parameters (qbits, rounding offset, the three MF/LS values of
 * the current QP row) are passed as kernel arguments, so the tables live in
 * exactly one place (src/tables.c).
 */
#ifndef AEG_KERNELS_H
#define AEG_KERNELS_H

static const char aeg_kernel_src[] =
"/* SAD of a batch of candidate blocks ------------------------------- */\n"
"__kernel void sad_batch(__global const uchar *cur, int cstride,\n"
"                        __global const uchar *ref, int rstride,\n"
"                        int bw, int bh, int count,\n"
"                        __global const short *mv, __global int *out)\n"
"{\n"
"    int i = get_global_id(0);\n"
"    int x, y, mx, my, sad = 0;\n"
"    if (i >= count) return;\n"
"    mx = mv[2 * i + 0];\n"
"    my = mv[2 * i + 1];\n"
"    for (y = 0; y < bh; y++) {\n"
"        __global const uchar *c = cur + y * cstride;\n"
"        __global const uchar *r = ref + (y + my) * rstride + mx;\n"
"        for (x = 0; x < bw; x++) {\n"
"            int d = (int)c[x] - (int)r[x];\n"
"            sad += d < 0 ? -d : d;\n"
"        }\n"
"    }\n"
"    out[i] = sad;\n"
"}\n"
"\n"
"/* 4x4 forward transform + quantisation ---------------------------- */\n"
"__kernel void tq_batch(__global const short *res, int nblk, int qbits,\n"
"                       int f, int mf0, int mf1, int mf2,\n"
"                       __global short *level, __global int *nz)\n"
"{\n"
"    int b = get_global_id(0);\n"
"    int i, t[16], d[16], nzc = 0;\n"
"    __global const short *r;\n"
"    __global short *l;\n"
"    if (b >= nblk) return;\n"
"    r = res + 16 * b;\n"
"    l = level + 16 * b;\n"
"    for (i = 0; i < 4; i++) {\n"
"        int d0 = r[i * 4 + 0], d1 = r[i * 4 + 1];\n"
"        int d2 = r[i * 4 + 2], d3 = r[i * 4 + 3];\n"
"        int t0 = d0 + d3, t1 = d1 + d2, t2 = d1 - d2, t3 = d0 - d3;\n"
"        t[i * 4 + 0] = t0 + t1;\n"
"        t[i * 4 + 1] = (t3 << 1) + t2;\n"
"        t[i * 4 + 2] = t0 - t1;\n"
"        t[i * 4 + 3] = t3 - (t2 << 1);\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int d0 = t[0 * 4 + i], d1 = t[1 * 4 + i];\n"
"        int d2 = t[2 * 4 + i], d3 = t[3 * 4 + i];\n"
"        int t0 = d0 + d3, t1 = d1 + d2, t2 = d1 - d2, t3 = d0 - d3;\n"
"        d[0 * 4 + i] = t0 + t1;\n"
"        d[1 * 4 + i] = (t3 << 1) + t2;\n"
"        d[2 * 4 + i] = t0 - t1;\n"
"        d[3 * 4 + i] = t3 - (t2 << 1);\n"
"    }\n"
"    for (i = 0; i < 16; i++) {\n"
"        int v = d[i];\n"
"        int a = v < 0 ? -v : v;\n"
"        int c = (i & 1) + ((i >> 2) & 1);\n"
"        int mf = c == 0 ? mf0 : (c == 1 ? mf1 : mf2);\n"
"        int lv = (a * mf + f) >> qbits;\n"
"        l[i] = (short)(v < 0 ? -lv : lv);\n"
"        nzc += (lv != 0);\n"
"    }\n"
"    nz[b] = nzc;\n"
"}\n"
"\n"
"/* inverse quantisation + inverse transform ------------------------ */\n"
"__kernel void iq_idct_batch(__global const short *level, int nblk, int sh,\n"
"                            int ls0, int ls1, int ls2, __global short *res)\n"
"{\n"
"    int b = get_global_id(0);\n"
"    int i, t[16], d[16];\n"
"    if (b >= nblk) return;\n"
"    for (i = 0; i < 16; i++) {\n"
"        int c = (i & 1) + ((i >> 2) & 1);\n"
"        int ls = c == 0 ? ls0 : (c == 1 ? ls1 : ls2);\n"
"        d[i] = level[16 * b + i] * ls << sh;\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int s0 = d[i * 4 + 0] + d[i * 4 + 2];\n"
"        int s1 = d[i * 4 + 0] - d[i * 4 + 2];\n"
"        int s2 = (d[i * 4 + 1] >> 1) - d[i * 4 + 3];\n"
"        int s3 = d[i * 4 + 1] + (d[i * 4 + 3] >> 1);\n"
"        t[i * 4 + 0] = s0 + s3;\n"
"        t[i * 4 + 1] = s1 + s2;\n"
"        t[i * 4 + 2] = s1 - s2;\n"
"        t[i * 4 + 3] = s0 - s3;\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int s0 = t[0 * 4 + i] + t[2 * 4 + i];\n"
"        int s1 = t[0 * 4 + i] - t[2 * 4 + i];\n"
"        int s2 = (t[1 * 4 + i] >> 1) - t[3 * 4 + i];\n"
"        int s3 = t[1 * 4 + i] + (t[3 * 4 + i] >> 1);\n"
"        res[16 * b + 0 * 4 + i] = (short)((s0 + s3 + 32) >> 6);\n"
"        res[16 * b + 1 * 4 + i] = (short)((s1 + s2 + 32) >> 6);\n"
"        res[16 * b + 2 * 4 + i] = (short)((s1 - s2 + 32) >> 6);\n"
"        res[16 * b + 3 * 4 + i] = (short)((s0 - s3 + 32) >> 6);\n"
"    }\n"
"}\n"
"\n"
"/* sum of squared differences, one work item per 8x8 tile ----------- */\n"
"__kernel void sse_batch(__global const uchar *a, int sa,\n"
"                        __global const uchar *b, int sb,\n"
"                        int tw, int th, int count, __global ulong *out)\n"
"{\n"
"    int i = get_global_id(0);\n"
"    int tx, ty, x, y;\n"
"    ulong sse = 0;\n"
"    if (i >= count) return;\n"
"    tx = i % tw;\n"
"    ty = i / tw;\n"
"    for (y = 0; y < 8; y++) {\n"
"        __global const uchar *pa = a + (ty * 8 + y) * sa + tx * 8;\n"
"        __global const uchar *pb = b + (ty * 8 + y) * sb + tx * 8;\n"
"        for (x = 0; x < 8; x++) {\n"
"            int d = (int)pa[x] - (int)pb[x];\n"
"            sse += (ulong)(d * d);\n"
"        }\n"
"    }\n"
"    out[i] = sse;\n"
"}\n";

#endif /* AEG_KERNELS_H */
