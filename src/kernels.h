/*
 * Device kernel source, shared by the OpenCL and CUDA backends.
 *
 * The kernels are written in the common subset of OpenCL C and CUDA C: only
 * one-dimensional global indices, plain scalar types and no local memory, so
 * the very same source string is compiled by clCreateProgramWithSource and by
 * the CUDA runtime (backend_cuda.c prepends a small typedef/macro header).
 * Keeping a single source of truth means the numerically sensitive integer
 * transforms can never drift between the two GPU paths -- and both are
 * bit-identical to the CPU reference implementation, which is what makes the
 * hybrid dispatch safe: moving a stage to the GPU cannot change the output
 * bitstream, only the speed at which it is produced.
 *
 * Quantisation parameters (qbits, rounding offset, the three MF/LS values of
 * the current QP row) are passed as kernel arguments, so the tables live in
 * exactly one place (src/tables.c).
 */
#ifndef AEG_KERNELS_H
#define AEG_KERNELS_H

static const char aeg_kernel_src[] =
"/* SAD of a batch of candidate blocks ------------------------------- */\n"
"__kernel void sad_batch(__global const uchar *cur, int cstride,\n"
"                        __global const uchar *ref, int rstride,\n"
"                        int bw, int bh, int count,\n"
"                        __global const short *mv, __global int *out)\n"
"{\n"
"    int i = get_global_id(0);\n"
"    int x, y, cx, cy, mx, my, sad = 0;\n"
"    if (i >= count) return;\n"
"    cx = mv[4 * i + 0];\n"
"    cy = mv[4 * i + 1];\n"
"    mx = mv[4 * i + 2];\n"
"    my = mv[4 * i + 3];\n"
"    for (y = 0; y < bh; y++) {\n"
"        __global const uchar *c = cur + (y + cy) * cstride + cx;\n"
"        __global const uchar *r = ref + (y + my) * rstride + mx;\n"
"        for (x = 0; x < bw; x++) {\n"
"            int d = (int)c[x] - (int)r[x];\n"
"            sad += d < 0 ? -d : d;\n"
"        }\n"
"    }\n"
"    out[i] = sad;\n"
"}\n"
"\n"
"/* 4x4 forward transform + quantisation ---------------------------- */\n"
"__kernel void tq_batch(__global const short *res, int nblk, int qbits,\n"
"                       int f, int mf0, int mf1, int mf2,\n"
"                       __global short *level, __global int *nz)\n"
"{\n"
"    int b = get_global_id(0);\n"
"    int i, t[16], d[16], nzc = 0;\n"
"    __global const short *r;\n"
"    __global short *l;\n"
"    if (b >= nblk) return;\n"
"    r = res + 16 * b;\n"
"    l = level + 16 * b;\n"
"    for (i = 0; i < 4; i++) {\n"
"        int d0 = r[i * 4 + 0], d1 = r[i * 4 + 1];\n"
"        int d2 = r[i * 4 + 2], d3 = r[i * 4 + 3];\n"
"        int t0 = d0 + d3, t1 = d1 + d2, t2 = d1 - d2, t3 = d0 - d3;\n"
"        t[i * 4 + 0] = t0 + t1;\n"
"        t[i * 4 + 1] = (t3 << 1) + t2;\n"
"        t[i * 4 + 2] = t0 - t1;\n"
"        t[i * 4 + 3] = t3 - (t2 << 1);\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int d0 = t[0 * 4 + i], d1 = t[1 * 4 + i];\n"
"        int d2 = t[2 * 4 + i], d3 = t[3 * 4 + i];\n"
"        int t0 = d0 + d3, t1 = d1 + d2, t2 = d1 - d2, t3 = d0 - d3;\n"
"        d[0 * 4 + i] = t0 + t1;\n"
"        d[1 * 4 + i] = (t3 << 1) + t2;\n"
"        d[2 * 4 + i] = t0 - t1;\n"
"        d[3 * 4 + i] = t3 - (t2 << 1);\n"
"    }\n"
"    /* The decoder's inverse transform is the transpose of the forward one, so\n"
"     * a block is transmitted transposed (see aeg_quant_4x4): slot (x, y) of\n"
"     * the level array holds the coefficient of (y, x).  The per-position\n"
"     * scale is symmetric in x and y, so only the index moves. */\n"
"    for (i = 0; i < 16; i++) {\n"
"        int v = d[(i & 3) * 4 + (i >> 2)];\n"
"        int a = v < 0 ? -v : v;\n"
"        int c = (i & 1) + ((i >> 2) & 1);\n"
"        int mf = c == 0 ? mf0 : (c == 1 ? mf1 : mf2);\n"
"        int lv = (a * mf + f) >> qbits;\n"
"        l[i] = (short)(v < 0 ? -lv : lv);\n"
"        nzc += (lv != 0);\n"
"    }\n"
"    nz[b] = nzc;\n"
"}\n"
"\n"
"/* inverse quantisation + inverse transform ------------------------ */\n"
"__kernel void iq_idct_batch(__global const short *level, int nblk, int sh,\n"
"                            int ls0, int ls1, int ls2, __global short *res)\n"
"{\n"
"    int b = get_global_id(0);\n"
"    int i, t[16], d[16];\n"
"    if (b >= nblk) return;\n"
"    for (i = 0; i < 16; i++) {\n"
"        int c = (i & 1) + ((i >> 2) & 1);\n"
"        int ls = c == 0 ? ls0 : (c == 1 ? ls1 : ls2);\n"
"        /* transposed, like aeg_dequant_4x4() */\n"
"        d[i] = level[16 * b + (i & 3) * 4 + (i >> 2)] * ls << sh;\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int s0 = d[i * 4 + 0] + d[i * 4 + 2];\n"
"        int s1 = d[i * 4 + 0] - d[i * 4 + 2];\n"
"        int s2 = (d[i * 4 + 1] >> 1) - d[i * 4 + 3];\n"
"        int s3 = d[i * 4 + 1] + (d[i * 4 + 3] >> 1);\n"
"        t[i * 4 + 0] = s0 + s3;\n"
"        t[i * 4 + 1] = s1 + s2;\n"
"        t[i * 4 + 2] = s1 - s2;\n"
"        t[i * 4 + 3] = s0 - s3;\n"
"    }\n"
"    for (i = 0; i < 4; i++) {\n"
"        int s0 = t[0 * 4 + i] + t[2 * 4 + i];\n"
"        int s1 = t[0 * 4 + i] - t[2 * 4 + i];\n"
"        int s2 = (t[1 * 4 + i] >> 1) - t[3 * 4 + i];\n"
"        int s3 = t[1 * 4 + i] + (t[3 * 4 + i] >> 1);\n"
"        res[16 * b + 0 * 4 + i] = (short)((s0 + s3 + 32) >> 6);\n"
"        res[16 * b + 1 * 4 + i] = (short)((s1 + s2 + 32) >> 6);\n"
"        res[16 * b + 2 * 4 + i] = (short)((s1 - s2 + 32) >> 6);\n"
"        res[16 * b + 3 * 4 + i] = (short)((s0 - s3 + 32) >> 6);\n"
"    }\n"
"}\n"
"\n"
"/* sum of squared differences, one work item per 8x8 tile ----------- */\n"
"__kernel void sse_batch(__global const uchar *a, int sa,\n"
"                        __global const uchar *b, int sb,\n"
"                        int tw, int th, int count, __global ulong *out)\n"
"{\n"
"    int i = get_global_id(0);\n"
"    int tx, ty, x, y;\n"
"    ulong sse = 0;\n"
"    (void)th;\n"
"    if (i >= count) return;\n"
"    tx = i % tw;\n"
"    ty = i / tw;\n"
"    for (y = 0; y < 8; y++) {\n"
"        __global const uchar *pa = a + (ty * 8 + y) * sa + tx * 8;\n"
"        __global const uchar *pb = b + (ty * 8 + y) * sb + tx * 8;\n"
"        for (x = 0; x < 8; x++) {\n"
"            int d = (int)pa[x] - (int)pb[x];\n"
"            sse += (ulong)(d * d);\n"
"        }\n"
"    }\n"
"    out[i] = sse;\n"
"}\n"
"\n"
"/* horizontal 6-tap *without* the shift and clip: the intermediate the\n"
" * two-dimensional half-pel position is built from.  A macro, not a function:\n"
" * NVRTC compiles this source as device code and a plain function would be a\n"
" * host function there, while the macro is valid in both languages. */\n"
"#define PL_HSUM(p) (((int)(p)[0] + (int)(p)[1]) * 20 - \\\n"
"                    ((int)(p)[-1] + (int)(p)[2]) * 5 + \\\n"
"                    ((int)(p)[-2] + (int)(p)[3]))\n"
"\n"
"/* one fractional-pel plane of the reference picture ---------------- */\n"
"__kernel void interp_plane(__global const uchar *ref, int rstride,\n"
"                           int w, int h, int pad, int which,\n"
"                           __global uchar *dst, int dstride)\n"
"{\n"
"    int ow = w + 2 * pad;\n"
"    int i = get_global_id(0);\n"
"    int ox, oy, x, y, x0, x1, y0, y1;\n"
"    if (i >= ow * (h + 2 * pad)) return;\n"
"    ox = i % ow - pad;\n"
"    oy = i / ow - pad;\n"
"    x0 = -pad + 2; x1 = w + pad - 4;\n"
"    y0 = -pad + 2; y1 = h + pad - 4;\n"
"    /* Outside the region whose taps stay inside the padded picture the plane\n"
"     * repeats its nearest computed sample, which is what the CPU reference\n"
"     * does -- motion compensation never reads that margin. */\n"
"    x = ox < x0 ? x0 : (ox > x1 ? x1 : ox);\n"
"    y = oy < y0 ? y0 : (oy > y1 ? y1 : oy);\n"
"    {\n"
"        __global const uchar *p = ref + y * rstride + x;\n"
"        int v;\n"
"        if (which == 1) {\n"
"            v = ((int)p[-2] + p[3] - 5 * ((int)p[-1] + p[2]) +\n"
"                 20 * ((int)p[0] + p[1]) + 16) >> 5;\n"
"        } else if (which == 2) {\n"
"            v = ((int)p[-2 * rstride] + p[3 * rstride] -\n"
"                 5 * ((int)p[-rstride] + p[2 * rstride]) +\n"
"                 20 * ((int)p[0] + p[rstride]) + 16) >> 5;\n"
"        } else {\n"
"            /* both axes: six vertical 6-taps over the *unshifted* horizontal\n"
"             * intermediates (H.264 8.4.2.2.1), one rounding at the end */\n"
"            int s = rstride;\n"
"            int sum = 0;\n"
"            sum += PL_HSUM(p - 2 * s);\n"
"            sum -= 5 * PL_HSUM(p - s);\n"
"            sum += 20 * PL_HSUM(p);\n"
"            sum += 20 * PL_HSUM(p + s);\n"
"            sum -= 5 * PL_HSUM(p + 2 * s);\n"
"            sum += PL_HSUM(p + 3 * s);\n"
"            v = (sum + 512) >> 10;\n"
"        }\n"
"        dst[oy * dstride + ox] = (uchar)(v < 0 ? 0 : (v > 255 ? 255 : v));\n"
"    }\n"
"}\n"
"\n"
"/* SATD of fractional-pel candidates, one work item per candidate ----\n"
" * The samples are interpolated from the reference planes exactly as\n"
" * aeg_mc_luma_p() does (H.264 8.4.2.2 quarter-pel combination), and the\n"
" * cost is the same 4x4 Hadamard sum of absolute differences as aeg_satd().\n"
" * This is the subpel stage of the motion search as a batch: the whole\n"
" * picture's candidate list in one launch. */\n"
"__kernel void satd_batch(__global const uchar *cur, int cstride,\n"
"                         __global const uchar *p0, __global const uchar *p1,\n"
"                         __global const uchar *p2, __global const uchar *p3,\n"
"                         int pstride, int pad, int bw, int bh,\n"
"                         __global const short *pos, int count,\n"
"                         __global int *out)\n"
"{\n"
"    /* which of the four planes each 1/4-pel position is built from */\n"
"    const int tab0[16] = {0, 1, 1, 1, 0, 1, 1, 1, 2, 3, 3, 3, 0, 1, 1, 1};\n"
"    const int tab1[16] = {0, 0, 1, 0, 2, 2, 3, 2, 2, 2, 3, 2, 2, 2, 3, 2};\n"
"    int i = get_global_id(0);\n"
"    int bx, by, ix, iy, fx, fy, idx, o1y, o2x, pl1, pl2;\n"
"    int sum = 0, sx, sy, x, y, ro;\n"
"    __global const uchar *pa, *pb;\n"
"    if (i >= count) return;\n"
"    bx = pos[4 * i + 0];\n"
"    by = pos[4 * i + 1];\n"
"    ix = bx + (pos[4 * i + 2] >> 2);\n"
"    iy = by + (pos[4 * i + 3] >> 2);\n"
"    fx = pos[4 * i + 2] & 3;\n"
"    fy = pos[4 * i + 3] & 3;\n"
"    idx = (fy << 2) | fx;\n"
"    pl1 = tab0[idx];\n"
"    pl2 = tab1[idx];\n"
"    o1y = (fy == 3) ? 1 : 0;\n"
"    o2x = (fx == 3) ? 1 : 0;\n"
"    /* the pictures are passed as whole padded allocations, so every\n"
"     * access is shifted by the border they carry */\n"
"    ro = pad * pstride + pad;\n"
"    for (sy = 0; sy < bh; sy += 4) {\n"
"        for (sx = 0; sx < bw; sx += 4) {\n"
"            int t[16], d[16], acc = 0;\n"
"            for (y = 0; y < 4; y++) {\n"
"                int r[4];\n"
"                for (x = 0; x < 4; x++) {\n"
"                    int px = ix + sx + x, py = iy + sy + y, v = 0, a, b;\n"
"                    if (idx == 0) {\n"
"                        v = p0[ro + py * pstride + px];\n"
"                    } else if ((idx & 5) == 0) {\n"
"                        if (pl1 == 1) pa = p1; else if (pl1 == 2) pa = p2; else pa = p3;\n"
"                        v = pa[ro + py * pstride + px];\n"
"                    } else {\n"
"                        if (pl1 == 0) pa = p0; else if (pl1 == 1) pa = p1;\n"
"                        else if (pl1 == 2) pa = p2; else pa = p3;\n"
"                        if (pl2 == 0) pb = p0; else if (pl2 == 1) pb = p1;\n"
"                        else if (pl2 == 2) pb = p2; else pb = p3;\n"
"                        a = pa[ro + (py + o1y) * pstride + px];\n"
"                        b = pb[ro + py * pstride + px + o2x];\n"
"                        v = (a + b + 1) >> 1;\n"
"                    }\n"
"                    r[x] = v - (int)cur[pad * cstride + pad +\n"
"                                       (by + sy + y) * cstride + bx + sx + x];\n"
"                }\n"
"                {\n"
"                    int a0 = r[0] + r[1], a1 = r[0] - r[1];\n"
"                    int a2 = r[2] + r[3], a3 = r[2] - r[3];\n"
"                    t[y * 4 + 0] = a0 + a2; t[y * 4 + 1] = a1 + a3;\n"
"                    t[y * 4 + 2] = a0 - a2; t[y * 4 + 3] = a1 - a3;\n"
"                }\n"
"            }\n"
"            for (x = 0; x < 4; x++) {\n"
"                int a0 = t[0 * 4 + x] + t[1 * 4 + x];\n"
"                int a1 = t[0 * 4 + x] - t[1 * 4 + x];\n"
"                int a2 = t[2 * 4 + x] + t[3 * 4 + x];\n"
"                int a3 = t[2 * 4 + x] - t[3 * 4 + x];\n"
"                d[0 * 4 + x] = a0 + a2; d[1 * 4 + x] = a1 + a3;\n"
"                d[2 * 4 + x] = a0 - a2; d[3 * 4 + x] = a1 - a3;\n"
"            }\n"
"            for (y = 0; y < 16; y++)\n"
"                acc += d[y] < 0 ? -d[y] : d[y];\n"
"            sum += (acc + 1) >> 1;\n"
"        }\n"
"    }\n"
"    out[i] = sum;\n"
"}\n"
;

#endif /* AEG_KERNELS_H */
